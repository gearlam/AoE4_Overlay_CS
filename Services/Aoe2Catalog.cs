        public static bool IsRanked(int matchType) => RankedMatchTypes.Contains(matchType);

        public static int LeaderboardId(int matchType) => matchType switch
        {
            2 or 60 => 1,
            3 or 4 or 5 or 61 => 2,
            7 or 8 or 9 or 67 or 68 or 69 => 4,
            26 or 86 => 13,
            27 or 28 or 29 or 87 or 88 or 89 => 14,
            10 => 5,
            _ => 3
        };

        public static string ModeName(int matchType, bool zh)
        {
            var size = matchType switch
            {
                3 or 7 or 27 or 67 or 87 or 121 or 123 or 125 => "2v2",
                4 or 8 or 28 or 68 or 88 => "3v3",
                5 or 9 or 29 or 69 or 89 => "4v4",
                _ => "1v1"
            };
            var kind = matchType switch
            {
                2 or 3 or 4 or 5 or 60 or 61 => zh ? "死斗" : "DM",
                26 or 27 or 28 or 29 or 86 or 87 or 88 or 89 => zh ? "帝国战争" : "EW",
                10 => zh ? "大逃杀" : "BR",
                66 or 67 or 68 or 69 => zh ? "手柄随机" : "Controller",
                120 or 121 => zh ? "庞贝" : "Pompeii",
                122 or 123 => "El Reinado",
                124 or 125 => "Londinium",
                _ => zh ? "随机图" : "RM"
            };
            return $"{kind} {size}";
        }

        public static string CivEnglish(int civilizationId) =>
            Civs.TryGetValue(civilizationId, out var civ) ? civ.En : "";

        public static string CivDisplay(int civilizationId, bool zh)
        {
            if (!Civs.TryGetValue(civilizationId, out var civ))
                return civilizationId > 0 ? $"Civ {civilizationId}" : "?";
            return zh ? civ.Zh : civ.En;
        }

        public static string MapName(string? raw, bool zh)
        {
            if (string.IsNullOrWhiteSpace(raw)) return "?";
            var name = raw.Trim();
            if (name.EndsWith(".rms2", StringComparison.OrdinalIgnoreCase))
                name = name[..^5];
            else if (name.EndsWith(".rms", StringComparison.OrdinalIgnoreCase))
                name = name[..^4];
            name = name.Replace('_', ' ').Trim();
            name = Regex.Replace(name, "([a-z])([A-Z])", "$1 $2");
            name = Regex.Replace(name, @"\s+", " ");
            if (zh && ZhMaps.TryGetValue(name, out var translated))
                return translated;
            return name;
        }
